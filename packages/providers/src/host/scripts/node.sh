#!/usr/bin/env bash
# install-node.sh — pinned Node.js from the official nodejs.org tarball (spike S3).
#
# Usage (as root):  install-node.sh [VERSION]      (default 24.22.3)
# Result: /opt/agentbox/vendor/node/<VERSION>/ (root-owned) and wrappers
#         /usr/local/bin/{node,npm,npx} that pin this exact node.
# Verification: SHASUMS256.txt from nodejs.org over HTTPS; set NODE_SHASUMS_SHA256 to also pin
# the checksum file itself (recommended for the release manifest), or NODE_TARBALL_SHA256 to
# pin the tarball hash directly.
# Idempotent: skips download when the tree exists and `node --version` matches.
set -euo pipefail

VERSION="${1:-24.22.3}"
BASE=/opt/agentbox/vendor/node
DEST="$BASE/$VERSION"

log() { printf '[install-node] %s\n' "$*"; }
die() { printf '[install-node] ERROR: %s\n' "$*" >&2; exit 1; }
[ "$(id -u)" -eq 0 ] || die "run as root"

case "$(uname -m)" in
  aarch64|arm64) ARCH=arm64 ;;
  x86_64|amd64) ARCH=x64 ;;
  *) die "unsupported arch $(uname -m)" ;;
esac
# .tar.gz instead of .tar.xz: no xz-utils needed on a minimal Ubuntu.
FILE="node-v$VERSION-linux-$ARCH.tar.gz"
URL="https://nodejs.org/dist/v$VERSION"

for p in curl ca-certificates; do
  dpkg-query -W -f='${Status}' "$p" 2>/dev/null | grep -q 'install ok installed' || {
    export DEBIAN_FRONTEND=noninteractive; apt-get -o DPkg::Lock::Timeout=600 update -qq; apt-get -o DPkg::Lock::Timeout=600 install -y -qq --no-install-recommends curl ca-certificates >/dev/null; break; }
done

if [ -x "$DEST/bin/node" ] && [ "$("$DEST/bin/node" --version)" = "v$VERSION" ]; then
  log "node v$VERSION already in $DEST"
else
  work="$(mktemp -d)"; trap 'rm -rf -- "$work"' EXIT
  log "downloading $FILE"
  curl -fsSL --retry 3 -o "$work/SHASUMS256.txt" "$URL/SHASUMS256.txt"
  if [ -n "${NODE_SHASUMS_SHA256:-}" ]; then
    echo "$NODE_SHASUMS_SHA256  $work/SHASUMS256.txt" | sha256sum -c --quiet - || die "SHASUMS256.txt hash mismatch"
  fi
  curl -fsSL --retry 3 -o "$work/$FILE" "$URL/$FILE"
  want="${NODE_TARBALL_SHA256:-$(awk -v f="$FILE" '$2 == f { print $1 }' "$work/SHASUMS256.txt")}"
  [ -n "$want" ] || die "$FILE not listed in SHASUMS256.txt"
  echo "$want  $work/$FILE" | sha256sum -c --quiet - || die "sha256 mismatch for $FILE"
  log "sha256 ok ($want)"
  install -d -m 0755 "$BASE"
  rm -rf -- "$work/tree"; mkdir "$work/tree"
  tar -o -xzf "$work/$FILE" -C "$work/tree" --strip-components=1
  chown -R root:root "$work/tree"; chmod -R go-w "$work/tree"
  rm -rf -- "$DEST.old"; [ ! -e "$DEST" ] || mv "$DEST" "$DEST.old"
  mv "$work/tree" "$DEST"; rm -rf -- "$DEST.old"
fi

# Wrappers (not symlinks): npm/npx are JS files resolved relative to the node tree, and a
# wrapper keeps PATH lookups of `node` from child processes pointing at the same pin.
for tool in node npm npx; do
  cat > "/usr/local/bin/$tool.new" <<EOF
#!/bin/sh
# agentbox wrapper: Node.js v$VERSION (generated by install-node.sh)
case ":\$PATH:" in *":$DEST/bin:"*) ;; *) PATH="$DEST/bin:\$PATH"; export PATH ;; esac
exec "$DEST/bin/$tool" "\$@"
EOF
  chmod 0755 "/usr/local/bin/$tool.new"; mv -f "/usr/local/bin/$tool.new" "/usr/local/bin/$tool"
done
# npm must never try to update itself or phone home on every call.
NPMRC="$DEST/etc/npmrc"   # global npmrc of this node tree ($PREFIX/etc/npmrc)
install -d -m 0755 "$DEST/etc"
printf 'update-notifier=false\nfund=false\naudit=false\n' > "$NPMRC"; chmod 0644 "$NPMRC"

log "ok: node $(/usr/local/bin/node --version), npm $(/usr/local/bin/npm --version)"
