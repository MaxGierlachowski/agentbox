#!/usr/bin/env bash
# install-paseo.sh — pinned Paseo CLI/daemon for agentbox (spike S3).
#
# Usage (as root):  install-paseo.sh [VERSION] [USER] [PASEO_HOME]
#   defaults: 0.17.3 agentbox /home/<USER>/.paseo
# Needs install-node.sh first (/usr/local/bin/node, npm).
# Result: /opt/agentbox/vendor/paseo/<VERSION>/ (npm global prefix, root-owned),
#         wrapper /usr/local/bin/paseo, and $PASEO_HOME/config.json with the agentbox daemon
#         settings merged in (listen 127.0.0.1:6767, relay off, web UI off, MCP injection on,
#         browser tools off). Other keys in config.json are preserved.
# Idempotent.
set -euo pipefail

VERSION="${1:-0.17.3}"
SVC_USER="${2:-agentbox}"
PASEO_HOME="${3:-/home/${SVC_USER}/.paseo}"
PREFIX="/opt/agentbox/vendor/paseo/$VERSION"

log() { printf '[install-paseo] %s\n' "$*"; }
die() { printf '[install-paseo] ERROR: %s\n' "$*" >&2; exit 1; }
[ "$(id -u)" -eq 0 ] || die "run as root"
command -v node >/dev/null && command -v npm >/dev/null || die "node/npm missing (run install-node.sh)"
id "$SVC_USER" >/dev/null 2>&1 || useradd --uid "${AGENTBOX_UID:-10001}" --create-home --shell /bin/bash "$SVC_USER"
SVC_GROUP="$(id -gn "$SVC_USER")"
SVC_HOME="$(getent passwd "$SVC_USER" | cut -d: -f6)"

installed="$(node -p "try{require('$PREFIX/lib/node_modules/@getpaseo/cli/package.json').version}catch(e){''}" 2>/dev/null || true)"
if [ "$installed" = "$VERSION" ] && [ -x "$PREFIX/bin/paseo" ]; then
  log "@getpaseo/cli $VERSION already in $PREFIX"
else
  log "npm install -g --prefix $PREFIX @getpaseo/cli@$VERSION"
  t0=$(date +%s)
  stage="$PREFIX.staging"; rm -rf -- "$stage"
  # Scripts must run: node-pty/sherpa-onnx/esbuild resolve their prebuilt binaries in install scripts.
  # Isolated npm cache so nothing lands in /root/.npm.
  npm_config_cache="$(mktemp -d)" npm_config_update_notifier=false npm install -g --prefix "$stage" --no-fund --no-audit --loglevel=error \
    "@getpaseo/cli@$VERSION"
  chown -R root:root "$stage"; chmod -R go-w "$stage"
  rm -rf -- "$PREFIX"; mv "$stage" "$PREFIX"
  log "installed in $(( $(date +%s) - t0 ))s ($(du -sh "$PREFIX" | cut -f1))"
fi

cat > /usr/local/bin/paseo.new <<EOF
#!/bin/sh
# agentbox wrapper: Paseo $VERSION (generated by install-paseo.sh)
export PASEO_HOME="\${PASEO_HOME:-$PASEO_HOME}"
exec $PREFIX/bin/paseo "\$@"
EOF
chmod 0755 /usr/local/bin/paseo.new; mv -f /usr/local/bin/paseo.new /usr/local/bin/paseo

# ---------------------------------------------------------------- daemon config (as the service user)
# `paseo daemon config set` is a local operation (no daemon needed), validates paths against the
# schema (exit 1 on unknown keys), keeps other keys, and a running daemon hot-reloads config.json.
install -d -o "$SVC_USER" -g "$SVC_GROUP" -m 0700 "$PASEO_HOME"
pcfg() { runuser -u "$SVC_USER" -- env HOME="$SVC_HOME" PASEO_HOME="$PASEO_HOME" \
           /usr/local/bin/paseo daemon config set "$1" "$2" --home "$PASEO_HOME" -q >/dev/null; }
pcfg daemon.listen 127.0.0.1:6767
pcfg daemon.relay.enabled false
pcfg daemon.mcp.injectIntoAgents true
pcfg daemon.browserTools.enabled false
pcfg daemon.cors.allowedOrigins '[]'        # default allows https://app.paseo.sh (hosted web app)
pcfg features.webUi.enabled false
pcfg features.dictation.enabled false       # default on: downloads a ~460 MB parakeet model from GitHub at start
pcfg features.voiceMode.enabled false
log "ok: paseo $(runuser -u "$SVC_USER" -- env HOME="$SVC_HOME" /usr/local/bin/paseo --version 2>/dev/null | head -1)"
