/**
 * agentbox override, applied with `-f upstream -f override`:
 * - proxy only on 127.0.0.1 (upstream publishes 80 and 443 on all interfaces)
 * - proxy also joins the workspace network as `plane-proxy`, so MetaMCP's Plane MCP reaches it
 * - sign-up disabled from the first boot
 */
export function planeComposeOverride(o: { workspaceNetwork: string }): string {
  return `# Generated by agentbox. Do not edit.
services:
  api:
    environment:
      ENABLE_SIGNUP: "0"
      ENABLE_MAGIC_LINK_LOGIN: "0"
  proxy:
    ports: !override
      - "127.0.0.1:${PLANE_PORT}:80"
    networks:
      default: {}
      agentbox:
        aliases: [plane-proxy]
networks:
  agentbox:
    external: true
    name: ${o.workspaceNetwork}
`
}

/** Values for `--env-file` (tmpfs). Upstream reads everything through ${VAR} interpolation. */
export function planeEnv(o: {
  webUrl: string
  secrets: {
    secretKey: string
    liveSecret: string
    dbPassword: string
    mqPassword: string
    minioSecret: string
  }
}): Record<string, string> {
  const db = encodeURIComponent(o.secrets.dbPassword)
  const mq = encodeURIComponent(o.secrets.mqPassword)
  const host = new URL(o.webUrl).hostname
  return {
    APP_RELEASE: PLANE_VERSION,
    APP_DOMAIN: host,
    WEB_URL: o.webUrl,
    CORS_ALLOWED_ORIGINS: o.webUrl,
    SITE_ADDRESS: ":80",
    TRUSTED_PROXIES: "0.0.0.0/0",
    SECRET_KEY: o.secrets.secretKey,
    LIVE_SERVER_SECRET_KEY: o.secrets.liveSecret,
    POSTGRES_PASSWORD: o.secrets.dbPassword,
    DATABASE_URL: `postgresql://plane:${db}@plane-db/plane`,
    RABBITMQ_PASSWORD: o.secrets.mqPassword,
    AMQP_URL: `amqp://plane:${mq}@plane-mq:5672/plane`,
    AWS_ACCESS_KEY_ID: "agentbox",
    AWS_SECRET_ACCESS_KEY: o.secrets.minioSecret,
    API_KEY_RATE_LIMIT: "120/minute",
  }
}

export interface PlaneBootstrapConfig {
  admin: { email: string; name: string; password: string }
  workspace: { name: string; slug: string }
  instanceName: string
}

/** The Python script with the config embedded (base64), to be piped into `manage.py shell`. */
export function planeBootstrapScript(cfg: Record<string, unknown>): string {
  const encoded = Buffer.from(JSON.stringify(cfg)).toString("base64")
  return bootstrapTemplate.replace("__AGENTBOX_CONFIG__", encoded)
}

export function parseBootstrapOutput(stdout: string): Record<string, unknown> {
  const err = stdout.match(/AGENTBOX_ERROR=(.*)/)?.[1]
  if (err) throw new Error(`Plane bootstrap: ${err}`)
  const line = stdout.match(/AGENTBOX_RESULT=(\{.*\})/)?.[1]
  if (!line) throw new Error(`Plane bootstrap printed no result:\n${stdout.slice(-800)}`)
  return JSON.parse(line) as Record<string, unknown>
}

function splitName(name: string) {
  const [first = name, ...rest] = name.trim().split(/\s+/)
  return { first_name: first, last_name: rest.join(" ") }
}

