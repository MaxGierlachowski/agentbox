export type StateGroup = "backlog" | "unstarted" | "started" | "completed" | "cancelled"
export interface PlaneState {
  id: string
  name: string
  group: StateGroup
  sequence?: number
}
export interface PlaneLabel {
  id: string
  name: string
}
export interface PlaneProject {
  id: string
  name: string
  identifier: string
}
export interface PlaneWorkItem {
  id: string
  name: string
  sequence_id: number
  description_stripped?: string | null
  description_html?: string | null
  state: string | PlaneState
  labels: (string | PlaneLabel)[]
  project: string
}

interface Page<T> {
  results: T[]
  next_cursor?: string
  next_page_results?: boolean
}

/** Plane REST API v1 with a personal API token (X-API-Key). */
export class PlaneClient {
  private readonly http: Http

  constructor(
    baseUrl: string,
    apiKey: string,
    readonly workspaceSlug: string,
    fetchImpl?: typeof fetch,
  ) {
    this.http = new Http({ baseUrl, fetch: fetchImpl, headers: { "x-api-key": apiKey } })
  }

  private ws(path: string) {
    return `/api/v1/workspaces/${this.workspaceSlug}${path}`
  }

  private async all<T>(path: string): Promise<T[]> {
    const out: T[] = []
    let cursor: string | undefined
    for (let i = 0; i < 50; i++) {
      const sep = path.includes("?") ? "&" : "?"
      const page = await this.http.json<Page<T> | T[]>(
        "GET",
        `${path}${sep}per_page=100${cursor ? `&cursor=${cursor}` : ""}`,
      )
      if (Array.isArray(page)) return page
      out.push(...page.results)
      if (!page.next_page_results || !page.next_cursor) break
      cursor = page.next_cursor
    }
    return out
  }

  projects() {
    return this.all<PlaneProject>(this.ws("/projects/"))
  }

  createProject(p: { name: string; identifier: string }) {
    return this.http.json<PlaneProject>("POST", this.ws("/projects/"), {
      body: { ...p, network: 0 },
    })
  }

  states(projectId: string) {
    return this.all<PlaneState>(this.ws(`/projects/${projectId}/states/`))
  }

  createState(projectId: string, s: { name: string; group: StateGroup; color: string }) {
    return this.http.json<PlaneState>("POST", this.ws(`/projects/${projectId}/states/`), {
      body: s,
    })
  }

  labels(projectId: string) {
    return this.all<PlaneLabel>(this.ws(`/projects/${projectId}/labels/`))
  }

  createLabel(projectId: string, l: { name: string; color: string }) {
    return this.http.json<PlaneLabel>("POST", this.ws(`/projects/${projectId}/labels/`), {
      body: l,
    })
  }

  workItems(projectId: string) {
    return this.all<PlaneWorkItem>(
      this.ws(`/projects/${projectId}/work-items/?expand=state,labels`),
    )
  }

  updateWorkItem(projectId: string, id: string, patch: { state?: string; labels?: string[] }) {
    return this.http.json<PlaneWorkItem>(
      "PATCH",
      this.ws(`/projects/${projectId}/work-items/${id}/`),
      { body: patch },
    )
  }

  comment(projectId: string, id: string, html: string) {
    return this.http.json("POST", this.ws(`/projects/${projectId}/work-items/${id}/comments/`), {
      body: { comment_html: html },
    })
  }
}

/** Project, label `claude`, `claude-failed` and the "In Review" state; idempotent. */
export async function ensurePlaneProject(
  client: PlaneClient,
  p: { name: string; identifier: string; label: string },
): Promise<{ project: PlaneProject; created: boolean }> {
  let project = (await client.projects()).find((x) => x.identifier === p.identifier)
  const created = !project
  if (!project) project = await client.createProject({ name: p.name, identifier: p.identifier })
  const labels = await client.labels(project.id)
  for (const [name, color] of [
    [p.label, "#d97706"],
    [`${p.label}-failed`, "#dc2626"],
  ] as const) {
    if (!labels.some((l) => l.name === name)) await client.createLabel(project.id, { name, color })
  }
  const states = await client.states(project.id)
  if (!states.some((s) => s.name.toLowerCase() === "in review")) {
    await client.createState(project.id, { name: "In Review", group: "started", color: "#8b5cf6" })
  }
  return { project, created }
}

