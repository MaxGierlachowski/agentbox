"use client"

import { Badge } from "@workspace/ui/components/badge"
import { Textarea } from "@workspace/ui/components/textarea"
import { cn } from "@workspace/ui/lib/utils"
import { LockIcon } from "lucide-react"
import { useId } from "react"

const START = "<!-- agentbox:generated -->"
const END = "<!-- /agentbox:generated -->"

/** Splits a SOUL.md into the editable text around the generated block. */
export function splitSoul(markdown: string): { before: string; after: string } {
  const s = markdown.indexOf(START)
  const e = markdown.indexOf(END)
  if (s === -1 || e === -1 || e < s) return { before: markdown.trimEnd(), after: "" }
  return {
    before: markdown.slice(0, s).trimEnd(),
    after: markdown.slice(e + END.length).trim(),
  }
}

/** Puts the user's text back around the generated block. */
export function joinSoul(before: string, generated: string, after: string): string {
  const block = generated.includes(START)
    ? generated.trim()
    : `${START}\n${generated.trim()}\n${END}`
  return `${[before.trimEnd(), block, after.trim()].filter(Boolean).join("\n\n")}\n`
}

const stripMarkers = (generated: string) => generated.replace(START, "").replace(END, "").trim()

export interface SoulEditorProps {
  /** Full SOUL.md, generated block included. */
  value: string
  /** The read-only block agentbox renders (with or without its markers). */
  generated: string
  onChange: (markdown: string) => void
  disabled?: boolean
  className?: string
}

/**
 * Editor for a SOUL.md: the user's sections are editable, the block between the
 * `agentbox:generated` markers is shown read-only in place (agentbox rewrites it on regenerate).
 */
export function SoulEditor({ value, generated, onChange, disabled, className }: SoulEditorProps) {
  const { before, after } = splitSoul(value)
  const id = useId()
  return (
    <div
      className={cn("overflow-hidden rounded-xl border bg-card", className)}
      data-slot="soul-editor"
    >
      <label htmlFor={`${id}-before`} className="sr-only">
        Your SOUL.md sections
      </label>
      <Textarea
        id={`${id}-before`}
        value={before}
        disabled={disabled}
        onChange={(e) => onChange(joinSoul(e.target.value, generated, after))}
        spellCheck
        className="field-sizing-content min-h-64 resize-y rounded-none border-0 bg-transparent font-mono text-[0.8rem] leading-relaxed shadow-none focus-visible:ring-0 dark:bg-transparent"
      />
      <section
        aria-label="Generated by agentbox (read-only)"
        className="border-y border-dashed bg-muted/50 px-3 py-3"
      >
        <div className="mb-2 flex items-center gap-2">
          <Badge variant="outline" className="gap-1 font-normal">
            <LockIcon className="size-3" aria-hidden />
            Generated by agentbox
          </Badge>
          <span className="text-muted-foreground text-xs">
            Facts about this box. Updated on every change; edits here would be overwritten.
          </span>
        </div>
        <pre className="whitespace-pre-wrap break-words font-mono text-[0.75rem] text-muted-foreground leading-relaxed">
          {stripMarkers(generated)}
        </pre>
      </section>
      <label htmlFor={`${id}-after`} className="sr-only">
        Notes after the generated block
      </label>
      <Textarea
        id={`${id}-after`}
        value={after}
        disabled={disabled}
        placeholder="Anything else Hermes should know (optional)"
        onChange={(e) => onChange(joinSoul(before, generated, e.target.value))}
        className="field-sizing-content min-h-16 resize-y rounded-none border-0 bg-transparent font-mono text-[0.8rem] leading-relaxed shadow-none focus-visible:ring-0 dark:bg-transparent"
      />
    </div>
  )
}
