// Drives the real config UI of a freshly installed box (no mock): claim → onboarding → Hermes UI.
// Logins are only started (the Claude link and the GitHub code must appear), never completed.
//
//   BOX=https://192.168.1.50:8443 OTP="word word …" bun e2e/vm/ui-smoke.ts
// Screenshots go to e2e/vm/screenshots/.
import { mkdir } from "node:fs/promises"
import { join } from "node:path"
import { chromium, expect, type Page } from "@playwright/test"

const BOX = process.env.BOX ?? "https://127.0.0.1:8443"
const OTP = (process.env.OTP ?? "").trim()
/** Resume on an already claimed box: sign in with E2E_PASSWORD and start at this step. */
const RESUME = process.env.RESUME_AT ?? ""
const PASSWORD = process.env.E2E_PASSWORD ?? "correct horse battery staple 42"
const OUT = join(import.meta.dir, "screenshots")
if (!OTP && !RESUME)
  throw new Error("Set OTP to the one-time code printed by `agentbox up` (or RESUME_AT)")

await mkdir(OUT, { recursive: true })
const browser = await chromium.launch()
const context = await browser.newContext({
  ignoreHTTPSErrors: true,
  viewport: { width: 1440, height: 1000 },
})
const page = await context.newPage()
let n = 0
const shot = async (name: string) => {
  n++
  await page.screenshot({
    path: join(OUT, `${String(n).padStart(2, "0")}-${name}.png`),
    fullPage: true,
  })
  console.log(`  📸 ${name}`)
}
const step = async (name: string, fn: () => Promise<void>) => {
  process.stdout.write(`… ${name}\n`)
  await fn()
  console.log(`✔ ${name}`)
}
const next = (p: Page) => p.getByRole("button", { name: "Continue" })

if (RESUME) {
  await step(`sign in and resume at ${RESUME}`, async () => {
    await page.goto(`${BOX}/login/`)
    await page.getByLabel("Password", { exact: true }).fill(PASSWORD)
    await page.getByRole("button", { name: "Sign in", exact: true }).click()
    await page.waitForURL((url) => !url.pathname.startsWith("/login"), { timeout: 30_000 })
    await page.goto(`${BOX}/onboarding/?step=${RESUME}`)
  })
} else {
  await step("claim with the console code", async () => {
    await page.goto(`${BOX}/setup/#otp=${OTP.replaceAll(" ", "-")}`)
    await expect(page.getByLabel("One-time code")).toHaveValue(OTP.replaceAll("-", " "))
    await page.getByLabel("Your name").fill("E2E Owner")
    await page.getByLabel("Email").fill("owner@example.org")
    await page.getByLabel("Password", { exact: true }).fill(PASSWORD)
    await shot("claim")
    await page.getByRole("button", { name: "Claim this box" }).click()
    await expect(page).toHaveURL(/\/onboarding\//, { timeout: 30_000 })
  })

  await step("connect AI: a real Claude sign-in link appears", async () => {
    await page.getByRole("button", { name: "Add account" }).click()
    await page.getByRole("button", { name: "Start sign-in" }).click()
    const link = page.getByRole("link", { name: /Open claude\.ai/ })
    await expect(link).toBeVisible({ timeout: 30_000 })
    expect(await link.getAttribute("href")).toMatch(/^https:\/\/claude\.ai\/oauth\/authorize\?/)
    await shot("connect-ai-claude-link")
    await next(page).click()
  })

  await step("who are you", async () => {
    await page.getByRole("button", { name: /Developer/ }).click()
    await page.getByLabel(/Describe your work/).fill("I build web apps and review pull requests.")
    await shot("role")
    await next(page).click()
  })

  await step("toolkit from the real catalog, library search", async () => {
    await expect(page.getByRole("checkbox", { name: "GitHub CLI" })).toBeChecked({
      timeout: 30_000,
    })
    await page.getByRole("combobox", { name: "Search the library" }).fill("linear")
    await expect(page.getByRole("option", { name: /Linear/ }).first()).toBeVisible({
      timeout: 15_000,
    })
    await shot("toolkit-search")
    await page.getByRole("combobox", { name: "Search the library" }).fill("")
    await next(page).click()
  })

  await step("SOUL composed", async () => {
    await expect(page.getByText("Generated by agentbox")).toBeVisible({ timeout: 30_000 })
    await shot("soul")
    await next(page).click()
  })

  await step("connect accounts: a real GitHub device code appears", async () => {
    const github = page.getByRole("region", { name: "GitHub", exact: true })
    await github.getByRole("button", { name: "Sign in to GitHub" }).click()
    await expect(github.getByText(/^[A-Z0-9]{4}-[A-Z0-9]{4}$/)).toBeVisible({ timeout: 30_000 })
    await shot("accounts-github-code")
    await next(page).click()
  })

  await step("SSH key", async () => {
    await page.getByRole("button", { name: "Generate ed25519 key" }).click()
    await expect(page.getByText(/^ssh-ed25519 /)).toBeVisible({ timeout: 30_000 })
    await shot("ssh")
    await next(page).click()
  })
}

if (!RESUME || RESUME === "agents") {
  await step("agents drafted and created", async () => {
    const create = page.getByRole("button", { name: /^Create (all|agent)$/ }).first()
    await expect(create).toBeVisible({ timeout: 180_000 })
    await shot("agents")
    await create.click()
    await expect(page.getByText(/created/).first()).toBeVisible({ timeout: 120_000 })
    await page.waitForTimeout(2000)
    await next(page).click()
  })
}

if (!RESUME || RESUME === "agents" || RESUME === "browser") {
  await step("box browser streams", async () => {
    const frame = page.frameLocator("iframe").first()
    await expect(frame.locator("canvas:visible").first()).toBeVisible({ timeout: 60_000 })
    await page.waitForTimeout(4000)
    await shot("browser-stream")
    await page.getByRole("button", { name: /^(Done|Continue)$/ }).click()
  })
}

await step("apply and hand-off to Hermes UI", async () => {
  await shot("apply")
  const install = page.getByRole("button", { name: /^Install/ })
  if (await install.isVisible()) {
    await install.click()
    await expect(page.getByText(/Succeeded|Failed/).first()).toBeVisible({ timeout: 600_000 })
    await shot("apply-done")
  }
  await page
    .getByRole("button", { name: /Open Hermes UI/ })
    .first()
    .click()
  await expect(page).toHaveURL(/\/hermes\//, { timeout: 60_000 })
  await page.waitForTimeout(5000)
  await shot("hermes-ui")
})

await step("devices: pair a laptop from the dialog", async () => {
  await page.goto(`${BOX}/devices/?pair=1`)
  const dialog = page.getByRole("dialog", { name: "Pair a device" })
  await expect(dialog.locator("svg[data-slot=qr-code]")).toBeVisible({ timeout: 30_000 })
  await shot("devices-pair-phone")
  await dialog.getByRole("tab", { name: "Laptop" }).click()
  const cmd =
    (await dialog
      .getByText(/agentbox connect [0-9a-f]+ --code/)
      .first()
      .textContent()) ?? ""
  await shot("devices-pair-laptop")
  const bin = process.env.AGENTBOX_BIN
  if (!bin) return
  const [, id, code] = cmd.match(/agentbox connect ([0-9a-f]+) --code (\S+)/) ?? []
  const proc = Bun.spawn(
    [
      bin,
      "connect",
      id as string,
      "--code",
      code as string,
      "--port",
      "18099",
      "--name",
      "ui-smoke",
    ],
    {
      env: { ...process.env, AGENTBOX_CONNECT_DIR: join(OUT, ".connect") },
      stdout: "pipe",
      stderr: "pipe",
    },
  )
  await expect(dialog.getByText(/is paired/)).toBeVisible({ timeout: 60_000 })
  await shot("devices-paired")
  const me = await fetch("http://localhost:18099/api/rpc/auth/me").then((r) => r.json())
  expect((me as { json: { via: string } }).json.via).toBe("device")
  proc.kill()
})

await browser.close()
console.log(`\nUI SMOKE PASSED → ${OUT}`)
